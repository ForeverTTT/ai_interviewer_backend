  add column if not exists finalize_attempts integer not null default 0,
  add column if not exists finalize_last_error text,
  add column if not exists finalize_last_error_stage text,
  add column if not exists finalize_request_id text,
  add column if not exists finalize_model text,
  add column if not exists finalize_started_at timestamptz,
  add column if not exists finalized_at timestamptz;

alter table public.interviews
  drop constraint if exists interviews_finalize_status_check;

alter table public.interviews
  add constraint interviews_finalize_status_check
  check (finalize_status in ('not_started', 'processing', 'failed', 'completed'));

update public.interviews
set
  finalize_status = 'completed',
  finalized_at = coalesce(finalized_at, updated_at, created_at)
where status = 'completed'
  and report_json is not null
  and finalize_status = 'not_started';

create or replace function public.claim_interview_finalize(
  p_interview_id uuid,
  p_request_id text,
  p_lock_seconds integer default 120
)
returns public.interviews
language plpgsql
security invoker
set search_path = public
as $$
declare
  claimed public.interviews;
begin
  update public.interviews
  set
    finalize_status = 'processing',
    finalize_attempts = finalize_attempts + 1,
    finalize_last_error = null,
    finalize_last_error_stage = null,
    finalize_request_id = left(p_request_id, 100),
    finalize_started_at = now()
  where id = p_interview_id
    and user_id = auth.uid()
    and not (status = 'completed' and report_json is not null)
    and (
      finalize_status <> 'processing'
      or finalize_started_at is null
      or finalize_started_at < now() - make_interval(secs => greatest(p_lock_seconds, 1))
    )
  returning * into claimed;

  return claimed;
end;
$$;

grant execute on function public.claim_interview_finalize(uuid, text, integer) to authenticated;

create table if not exists public.interview_events (
  id bigint generated by default as identity primary key,
  interview_id uuid not null references public.interviews(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  request_id text,
  event_type text not null,
  event_source text not null check (event_source in ('client', 'backend')),
  stage text,
  model text,
  http_status integer,
  error_code text,
  error_message text,
  duration_ms integer,
  message_count integer,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists interview_events_interview_created_idx
  on public.interview_events(interview_id, created_at);

create index if not exists interview_events_user_created_idx
  on public.interview_events(user_id, created_at desc);

create index if not exists interview_events_request_idx
  on public.interview_events(request_id)
  where request_id is not null;

alter table public.interview_events enable row level security;

drop policy if exists "users read own interview events" on public.interview_events;
create policy "users read own interview events"
  on public.interview_events
  for select
  to authenticated
  using (auth.uid() = user_id);

revoke insert, update, delete on public.interview_events from anon, authenticated;
grant select on public.interview_events to authenticated;

comment on table public.interview_events is
  'Append-only diagnostic lifecycle for interview finalization. No prompts, tokens, or raw audio.';
