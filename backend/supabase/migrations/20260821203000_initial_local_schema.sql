create extension if not exists pgcrypto;

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  resume_text text not null default '',
  resume_notes text not null default '',
  tokens integer not null default 1000 check (tokens >= 0),
  profile_json jsonb not null default '{}'::jsonb,
  job_search_status text not null default 'seeking',
  avatar_id text,
  resume_coach jsonb,
  resume_updated_at timestamptz,
  mastered_questions jsonb not null default '[]'::jsonb,
  daily_streak integer not null default 0,
  last_activity_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.interviews (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  position text not null,
  job_description text not null default '',
  language text not null,
  duration integer not null check (duration > 0),
  resume_snapshot text,
  status text not null default 'in_progress',
  transcript_json jsonb not null default '[]'::jsonb,
  report_json jsonb,
  report_markdown text,
  report_ui_locale text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index interviews_user_created_idx on public.interviews(user_id, created_at desc);

create table public.interviews_backup (
  id uuid primary key default gen_random_uuid(),
  original_id uuid not null unique,
  user_id uuid not null,
  position text not null,
  job_description text not null default '',
  language text not null,
  duration integer not null,
  resume_snapshot text,
  status text not null default 'in_progress',
  transcript_json jsonb,
  report_json jsonb,
  created_at timestamptz not null default now()
);

create table public.gallup_questions (
  id bigint generated by default as identity primary key,
  index_number integer not null unique,
  category text not null,
  question_zh text not null,
  question_en text not null,
  question_de text not null
);

create table public.gallup_analysis_content (
  id bigint generated by default as identity primary key,
  domain_key text not null,
  score_tier text not null,
  lang text not null,
  content jsonb not null default '[]'::jsonb,
  unique(domain_key, score_tier, lang)
);

create table public.gallup_responses (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null unique references auth.users(id) on delete cascade,
  answers jsonb not null default '{}'::jsonb,
  results jsonb not null default '[]'::jsonb,
  status text not null default 'not_started',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.interview_experiences (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  type text not null,
  company text not null,
  location text,
  position text not null,
  department text,
  date text not null,
  language text,
  rounds jsonb not null default '[]'::jsonb,
  result text,
  salary text,
  reflection text,
  publisher text,
  created_at timestamptz not null default now()
);

create index interview_experiences_created_idx on public.interview_experiences(created_at desc);
create index interview_experiences_user_created_idx on public.interview_experiences(user_id, created_at desc);

create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger profiles_set_updated_at before update on public.profiles
for each row execute function public.set_updated_at();
create trigger interviews_set_updated_at before update on public.interviews
for each row execute function public.set_updated_at();

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id) values (new.id) on conflict (id) do nothing;
  return new;
end;
$$;

create trigger on_auth_user_created after insert on auth.users
for each row execute function public.handle_new_user();

create or replace function public.deduct_user_tokens(p_user_id uuid, p_amount integer)
returns integer language plpgsql security definer set search_path = public as $$
declare remaining integer;
begin
  update public.profiles
  set tokens = greatest(0, tokens - greatest(0, p_amount))
  where id = p_user_id
  returning tokens into remaining;
  return remaining;
end;
$$;

alter table public.profiles enable row level security;
alter table public.interviews enable row level security;
alter table public.gallup_responses enable row level security;
alter table public.interview_experiences enable row level security;

create policy "users read own profile" on public.profiles for select to authenticated using (auth.uid() = id);
create policy "users insert own profile" on public.profiles for insert to authenticated with check (auth.uid() = id);
create policy "users update own profile" on public.profiles for update to authenticated using (auth.uid() = id) with check (auth.uid() = id);
create policy "users manage own interviews" on public.interviews for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "users manage own gallup response" on public.gallup_responses for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "anyone reads experiences" on public.interview_experiences for select to anon, authenticated using (true);
create policy "users insert own experiences" on public.interview_experiences for insert to authenticated with check (auth.uid() = user_id);
create policy "users delete own experiences" on public.interview_experiences for delete to authenticated using (auth.uid() = user_id);

grant usage on schema public to anon, authenticated, service_role;
grant select on public.gallup_questions, public.gallup_analysis_content, public.interview_experiences to anon, authenticated;
grant select, insert, update on public.profiles, public.interviews, public.gallup_responses to authenticated;
grant insert, delete on public.interview_experiences to authenticated;
grant all on all tables in schema public to service_role;
grant usage, select on all sequences in schema public to anon, authenticated, service_role;
grant execute on function public.deduct_user_tokens(uuid, integer) to authenticated, service_role;

